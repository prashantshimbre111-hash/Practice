package switchcase;

public class practice{
	public static void main(String[] args) {
		
		int m = 2;
		
		switch(m) {
		
		case 1:
			System.out.println("red");
			break;
			
		case 2:
			System.out.println("blue");
			break;
			
		case 3:
			System.out.println("green");
			break;
			
		default:
			System.out.println("please enter proper number");
		
		}
		
		
	}

}
